"""Build Nature_Deck_Skeleton_EY.pptx v5.0 from v4.5: new page 4 (exposure panel + grid), page 5 'Why EY' placeholders only,
abbreviation-key line on pages 2-4.  Usage: python build_skeleton_v50.py SKEL_IN SKEL_OUT WORKDIR"""
import sys, os, json, subprocess, shutil
from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
HERE = os.path.dirname(os.path.abspath(__file__))
SKEL, OUT, WD = sys.argv[1:4]
os.makedirs(WD, exist_ok=True)
# placeholder chart data (replaced via Edit Data in Prompt 9c)
D = {'D': [[f'Sector {n}  0.0%', 0.0 if n % 3 else 0.01, round(0.5 / n, 3)] for n in range(1, 13)]}
json.dump(D, open(f'{WD}/chartD.json', 'w'))
run = lambda *a: subprocess.run(list(a), check=True, cwd=HERE)
run('node', 'page4_exposure.js', f'{WD}/chartD.json', f'{WD}/p4.pptx')
run('node', 'page5_whyey.js', f'{WD}/p5.pptx')
run('python3', 'replace_page.py', SKEL, '4', f'{WD}/p4.pptx', f'{WD}/s1.pptx')
run('python3', 'replace_page.py', f'{WD}/s1.pptx', '5', f'{WD}/p5.pptx', f'{WD}/s2.pptx')
p = Presentation(f'{WD}/s2.pptx')
for i, a, b in ((4, 'How EY can support', 'Why EY'), (2, 'Growth sectors vs ', 'Growth sectors compared with ')):
    for sh in p.slides[i].shapes:
        if sh.has_text_frame:
            for para in sh.text_frame.paragraphs:
                for r in para.runs:
                    r.text = r.text.replace(a, b)
for i, tok in ((1, '{{s1_key}}'), (2, '{{s2_key}}')):
    tb = p.slides[i].shapes.add_textbox(Inches(0.58), Inches(6.87), Inches(11.46), Inches(0.26)); tb.name = 'abbreviation-key'
    tf = tb.text_frame; tf.word_wrap = True
    for m in ('margin_left', 'margin_right', 'margin_top', 'margin_bottom'): setattr(tf, m, 0)
    r = tf.paragraphs[0].add_run(); r.text = tok; r.font.size = Pt(6.5); r.font.name = 'EYInterstate Light'; r.font.color.rgb = RGBColor(0xBF, 0xBF, 0xC7)
# page 5 speaker notes
n = p.slides[4].notes_slide.notes_text_frame
n.text = 'Why EY – written by the EY team, not generated by the agent. Replace every [EY team: …] placeholder and delete any that are not needed.'
p.save(OUT); print('skeleton v5.0 ->', OUT)
